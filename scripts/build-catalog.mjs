function glyphShapeSvg(shape, { size = 48, fill = "var(--rc)" } = {}) {
  return (
    `<svg viewBox="0 0 24 24" width="${size}" height="${size}" aria-hidden="true" style="opacity:.95">` +
    `<path d="${shape.d}" fill="${fill}"${shape.eo ? ' fill-rule="evenodd"' : ""}/>` +
    `</svg>`
  );
}

