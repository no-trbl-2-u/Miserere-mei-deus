// Keyword vocabulary bolded inside the PAID sentence (the card overlay defines
// them; the face just flags that they ARE keywords). Longest-first so multi-word
// keywords win the match.
const KEYWORD_WORDS = [
  "HEAL SELF", "BLEED", "GUARD",
  "DOT", "PIP", "PIPS", "HEAL",
  // S3 (D43) — A Plain Word's VULNERABLE.
  "VULNERABLE",
  // Revamp R5 (D49) dropped MARK, DRAW and CLEANSE with the consumables.
  // Revamp R4 (D45) dropped POISON, DOOM, QUARTER, STAGGER, PLEA, WRATH and
  // CHAIN with the signature skills that last carried them.
  // The keyword purge (2026-09-28) dropped RIPOSTE, FORETELL and PIERCE.
  // The keyword audit (2026-09-27, after the card purge) dropped every word
  // whose registry gloss left with the purged cards (BACKFIRE, REAP, SOUL(S),
  // CHARGE(S), ECHO, FORGE, SIPHON, RUPTURE, PROLONG, RECALL, SENTENCE,
  // CONDEMN, RELENT, THORNS, TICK, PERORATE, KINDLE, RECOIL, FALLEN, OMEN,
  // MILL, STRIP BUFF): bolding them would imply a keyword the overlay cannot define.
].sort((a, b) => b.length - a.length);

function boldKeywords(text) {
  if (!text) return "";
  const esc = KEYWORD_WORDS.map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  const re = new RegExp(`\\b(${esc.join("|")})\\b`, "gi");
  // Split into keyword / non-keyword runs and escape each part before joining.
  const out = [];
  let last = 0;
  let m;
  while ((m = re.exec(text)) !== null) {
    if (m.index > last) out.push(escapeHtml(text.slice(last, m.index)));
    out.push(`<b>${escapeHtml(m[0])}</b>`);
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push(escapeHtml(text.slice(last)));
  return out.join("");
}

function chipVal(chips, key) {
  const c = (chips || []).find((x) => x.k === key);
  return c ? c.v : "";
}

