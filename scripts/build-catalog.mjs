function load(name) {
  const path = join(DATA, `${name}.json`);
  if (!existsSync(path)) {
    console.warn(`catalog: missing ${name}.json — run "npm run catalog:export" first.`);
    return [];
  }
  return JSON.parse(readFileSync(path, "utf8"));
}

